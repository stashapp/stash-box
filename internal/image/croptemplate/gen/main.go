// Command gen writes templates_gen.go: the parsed geometry of every .psd
// under templates/, as a Go table. Run via go:generate from the package
// directory whenever a template file changes; the drift test in loader_test.go
// fails if this output and the files ever disagree.
package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/stashapp/stash-box/internal/image/croptemplate"
	"github.com/stashapp/stash-box/internal/image/croptemplate/psdparse"
)

func main() {
	entries, err := os.ReadDir("templates")
	if err != nil {
		log.Fatal(err)
	}

	keys := make([]string, 0, len(entries))
	templates := make(map[string]croptemplate.Template, len(entries))
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasSuffix(name, croptemplate.TemplateExt) {
			continue
		}
		data, err := os.ReadFile(filepath.Join("templates", name))
		if err != nil {
			log.Fatal(err)
		}
		template, err := psdparse.Parse(data)
		if err != nil {
			log.Fatalf("template %s: %v", name, err)
		}
		key := strings.TrimSuffix(name, croptemplate.TemplateExt)
		keys = append(keys, key)
		templates[key] = template
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	b.WriteString("// The geometry of templates/*.psd, parsed offline by ./gen so the server\n")
	b.WriteString("// carries no PSD parser. Regenerate with go generate after changing a\n")
	b.WriteString("// template file; the drift test compares this table against the files.\n\n")
	b.WriteString("package croptemplate\n\n")
	b.WriteString("func builtinTemplates() map[string]Template {\n\treturn map[string]Template{\n")
	for _, key := range keys {
		t := templates[key]
		fmt.Fprintf(&b, "\t\t%q: {\n\t\t\tWidth:  %d,\n\t\t\tHeight: %d,\n\t\t\tGuides: []Guide{\n", key, t.Width, t.Height)
		for _, g := range t.Guides {
			fmt.Fprintf(&b, "\t\t\t\t{Axis: %q, Position: %v, Role: %q, Label: %q},\n",
				string(g.Axis), g.Position, string(g.Role), g.Label)
		}
		b.WriteString("\t\t\t},\n\t\t},\n")
	}
	b.WriteString("\t}\n}\n")

	if err := os.WriteFile("templates_gen.go", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}
